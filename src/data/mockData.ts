// Today's date helper
const getTodayDateString = () => {
  const d = new Date();
  return d.toISOString().split('T')[0];
};

const getRelativeDateString = (daysOffset: number) => {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  return d.toISOString().split('T')[0];
};

